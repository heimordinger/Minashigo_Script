"""Typed failures.  Codes are stable API; prose is not."""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any


class ErrorCode(str, Enum):
    MODEL_UNAVAILABLE = "MODEL_UNAVAILABLE"
    MODEL_PROTOCOL_ERROR = "MODEL_PROTOCOL_ERROR"
    UNSUPPORTED_PROTOCOL_VERSION = "UNSUPPORTED_PROTOCOL_VERSION"
    INVALID_ACTION = "INVALID_ACTION"
    INVALID_ARGUMENTS = "INVALID_ARGUMENTS"
    INVALID_STATE_TRANSITION = "INVALID_STATE_TRANSITION"
    UNSUPPORTED_SCHEMA_VALUE = "UNSUPPORTED_SCHEMA_VALUE"
    TASK_NOT_FOUND = "TASK_NOT_FOUND"
    TURN_NOT_FOUND = "TURN_NOT_FOUND"
    RESOURCE_NOT_FOUND = "RESOURCE_NOT_FOUND"
    STALE_RESOURCE = "STALE_RESOURCE"
    INVALID_RESOURCE = "INVALID_RESOURCE"
    REVISION_CONFLICT = "REVISION_CONFLICT"
    VIEWPORT_REVISION_CHANGED = "VIEWPORT_REVISION_CHANGED"
    CAPABILITY_NOT_FOUND = "CAPABILITY_NOT_FOUND"
    CAPABILITY_UNAVAILABLE = "CAPABILITY_UNAVAILABLE"
    CAPABILITY_VERSION_CHANGED = "CAPABILITY_VERSION_CHANGED"
    CAPABILITY_SCHEMA_MISMATCH = "CAPABILITY_SCHEMA_MISMATCH"
    PERMISSION_REQUIRED = "PERMISSION_REQUIRED"
    PERMISSION_EXPIRED = "PERMISSION_EXPIRED"
    PERMISSION_SCOPE_MISMATCH = "PERMISSION_SCOPE_MISMATCH"
    EVIDENCE_INSUFFICIENT = "EVIDENCE_INSUFFICIENT"
    EVIDENCE_CONFLICT = "EVIDENCE_CONFLICT"
    INVALID_COORDINATES = "INVALID_COORDINATES"
    PLAN_INVALID = "PLAN_INVALID"
    INTERACTION_NOT_JUSTIFIED = "INTERACTION_NOT_JUSTIFIED"
    COMPLETION_NOT_PROVEN = "COMPLETION_NOT_PROVEN"
    LOGIC_CONFIRMATION_REQUIRED = "LOGIC_CONFIRMATION_REQUIRED"
    #: 第一层任务定向闸（设计 §3）：用户没有明确脚本意图却要进脚本流程；
    #: 任务动作没有带完整 orientation（可修复一次，要求重新提交）。
    SCRIPT_INTENT_NOT_EXPLICIT = "SCRIPT_INTENT_NOT_EXPLICIT"
    TASK_ORIENTATION_REQUIRED = "TASK_ORIENTATION_REQUIRED"
    #: 主轮**总**缺 orientation 次数超上限（独立诊断码）：与"同一个动作重交仍缺"
    #: 分开记，免得把两个不同动作的首次漏填误判成同一动作重交失败。
    TASK_ORIENTATION_EXCESSIVE = "TASK_ORIENTATION_EXCESSIVE"
    #: Phase B3 图接管（asset_analysis）的稳定诊断码。
    GRAPH_NODE_ACTION_NOT_ALLOWED = "GRAPH_NODE_ACTION_NOT_ALLOWED"
    GRAPH_EVIDENCE_QUERY_NOT_ALLOWED = "GRAPH_EVIDENCE_QUERY_NOT_ALLOWED"
    GRAPH_HUMAN_INPUT_PREMATURE = "GRAPH_HUMAN_INPUT_PREMATURE"
    GRAPH_NODE_NO_PROGRESS = "GRAPH_NODE_NO_PROGRESS"
    GRAPH_EXECUTION_FAILED = "GRAPH_EXECUTION_FAILED"
    TOOL_FAILURE = "TOOL_FAILURE"
    TOOL_TIMEOUT = "TOOL_TIMEOUT"
    TOOL_NO_PROGRESS = "TOOL_NO_PROGRESS"
    #: Phase B4（设计 §4.8）：工具边界**分阶段**失败，禁止只回裸 ``TOOL_FAILURE``。
    RESOURCE_BINDING_FAILED = "RESOURCE_BINDING_FAILED"
    RESOURCE_ARGUMENT_NOT_MATERIALIZED = "RESOURCE_ARGUMENT_NOT_MATERIALIZED"
    RESOURCE_NAME_AMBIGUOUS = "RESOURCE_NAME_AMBIGUOUS"
    ARGUMENT_CONTRACT_MISMATCH = "ARGUMENT_CONTRACT_MISMATCH"
    TOOL_EXECUTION_FAILED = "TOOL_EXECUTION_FAILED"
    TOOL_RESULT_INVALID = "TOOL_RESULT_INVALID"
    ACTION_CANCELLED = "ACTION_CANCELLED"
    ACTION_RESULT_QUARANTINED = "ACTION_RESULT_QUARANTINED"
    BUDGET_EXCEEDED = "BUDGET_EXCEEDED"
    COMMIT_REJECTED = "COMMIT_REJECTED"
    COMMIT_CONFLICT = "COMMIT_CONFLICT"
    RUNTIME_ERROR = "RUNTIME_ERROR"


@dataclass
class DomainError(Exception):
    code: ErrorCode
    message: str
    details: dict[str, Any] | None = None
    recoverable: bool = False

    def __str__(self) -> str:
        return f"{self.code.value}: {self.message}"
